# Universal PubChem Fetch Function (Fetches ANY Drug Worldwide)
@st.cache_data(ttl=3600)
def fetch_universal_pubchem_data(drug_name):
    clean_name = drug_name.strip()
    url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{clean_name}/property/MolecularWeight,XLogP,HBondDonorCount,HBondAcceptorCount,RotatableBondCount/JSON"
    try:
        res = requests.get(url, timeout=5)
        if res.status_code == 200:
            props = res.json()['PropertyTable']['Properties'][0]
            mw = float(props.get('MolecularWeight', 300.0))
            logp = float(props.get('XLogP', 2.0))
            h_donors = int(props.get('HBondDonorCount', 2))
            h_acceptors = int(props.get('HBondAcceptorCount', 4))
            rot_bonds = int(props.get('RotatableBondCount', 3))
            
            # Universal Rule-based Estimation
            if logp > 2.5 and mw > 350:
                bcs = "Class II (Low Solubility, High Permeability)"
            elif logp <= 2.5 and mw <= 350:
                bcs = "Class I (High Solubility, High Permeability)"
            elif logp <= 2.5 and mw > 350:
                bcs = "Class III (High Solubility, Low Permeability)"
            else:
                bcs = "Class IV (Low Solubility, Low Permeability)"

            return {
                "success": True,
                "MW": mw,
                "LogP": logp,
                "HBondDonorCount": h_donors,
                "HBondAcceptorCount": h_acceptors,
                "RotatableBonds": rot_bonds,
                "BCS_Class": bcs
            }
        else:
            return {"success": False, "error": f"API HTTP Error {res.status_code}"}
    except Exception as e:
        return {"success": False, "error": str(e)}

