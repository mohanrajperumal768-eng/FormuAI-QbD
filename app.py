def convert_pdb_to_pdbqt(pdb_text, molecule_name="LIGAND"):
    lines = pdb_text.splitlines()
    pdbqt_lines = [
        f"REMARK  FormuAI-QbD Generated Docking Ready File",
        f"REMARK  Compound: {molecule_name}",
        f"REMARK  Format: AutoDock PDBQT (v4.2)",
        "ROOT"
    ]
    atom_count = 0
    for line in lines:
        if line.startswith("ATOM") or line.startswith("HETATM"):
            atom_count += 1
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip() or "LIG"
            chain_id = line[21:22].strip() or "A"
            res_num = line[22:26].strip() or "1"
            try:
                x = float(line[30:38].strip())
                y = float(line[38:46].strip())
                z = float(line[46:54].strip())
            except ValueError:
                continue

            element = atom_name[0].upper()
            if element not in ['C', 'N', 'O', 'S', 'P', 'F', 'Cl', 'Br', 'I', 'H']:
                element = 'C'
            
            ad_type = element
            if element == 'C':
                ad_type = 'A' if 'AR' in line.upper() else 'C'
            elif element == 'O':
                ad_type = 'OA'
            elif element == 'N':
                ad_type = 'NA'

            charge = 0.000
            pdbqt_line = f"ATOM  {atom_count:>5} {atom_name:<4} {res_name:>3} {chain_id}{res_num:>4}    {x:>8.3f}{y:>8.3f}{z:>8.3f}  1.00  0.00    {charge:>6.3f} {ad_type:<2}"
            pdbqt_lines.append(pdbqt_line)

    pdbqt_lines.append("ENDROOT")
    pdbqt_lines.append(f"TORSDOF {max(0, atom_count // 3)}")
    return "\n".join(pdbqt_lines)

def fetch_pubchem_data(drug_name):
    raw_query = str(drug_name).strip()
    if not raw_query:
        return {"success": False, "error": "Empty Query"}
    
    clean_name = urllib.parse.quote(raw_query)
    headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}
    
    url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{clean_name}/property/CID,MolecularFormula,MolecularWeight,XLogP,HBondDonorCount,HBondAcceptorCount,CanonicalSMILES/JSON"
    
    try:
        res = requests.get(url, headers=headers, timeout=6)
        corrected = False
        autocorrect_term = raw_query
        
        if res.status_code != 200:
            sug_url = f"https://pubchem.ncbi.nlm.nih.gov/rest/autocomplete/compound/{clean_name}/json?limit=1"
            sug_res = requests.get(sug_url, headers=headers, timeout=5)
            if sug_res.status_code == 200 and sug_res.json().get('dictionary_terms'):
                autocorrect_term = sug_res.json()['dictionary_terms'][0]
                clean_name = urllib.parse.quote(autocorrect_term)
                url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{clean_name}/property/CID,MolecularFormula,MolecularWeight,XLogP,HBondDonorCount,HBondAcceptorCount,CanonicalSMILES/JSON"
                res = requests.get(url, headers=headers, timeout=6)
                corrected = True

        if res.status_code == 200:
            props = res.json()['PropertyTable']['Properties'][0]
            mw = float(props.get('MolecularWeight', 300.0))
            logp = float(props.get('XLogP', 2.0))
            bcs = "Class II" if logp > 2.5 and mw > 350 else ("Class I" if logp <= 2.5 and mw <= 350 else "Class III")
            return {
                "success": True,
                "name": autocorrect_term.capitalize(),
                "autocorrected": corrected,
                "cid": props.get('CID', 0),
                "formula": props.get('MolecularFormula', 'N/A'),
                "smiles": props.get('CanonicalSMILES', 'N/A'),
                "mw": mw,
                "logp": logp,
                "h_donors": int(props.get('HBondDonorCount', 2)),
                "h_acceptors": int(props.get('HBondAcceptorCount', 4)),
                "bcs": bcs
            }
        return {"success": False, "error": f"Compound not found (HTTP {res.status_code})"}
    except Exception as e:
        return {"success": False, "error": str(e)}

