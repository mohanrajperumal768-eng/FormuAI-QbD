# Helper Function: PDB to Docking-Ready PDBQT Format
def convert_pdb_to_pdbqt(pdb_text, molecule_name="LIGAND"):
    lines = pdb_text.splitlines()
    pdbqt_lines = [
        f"REMARK  FormuAI-QbD Generated Docking Ready File",
        f"REMARK  Compound: {molecule_name}",
        f"REMARK  Format: AutoDock PDBQT (v4.2)",
        "ROOT"
    ]
    atom_count = 0
    for line in lines:
        if line.startswith("ATOM") or line.startswith("HETATM"):
            atom_count += 1
            atom_num = line[6:11].strip()
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip() or "LIG"
            chain_id = line[21:22].strip() or "A"
            res_num = line[22:26].strip() or "1"
            try:
                x = float(line[30:38].strip())
                y = float(line[38:46].strip())
                z = float(line[46:54].strip())
            except ValueError:
                continue

            element = atom_name[0].upper()
            if element not in ['C', 'N', 'O', 'S', 'P', 'F', 'Cl', 'Br', 'I', 'H']:
                element = 'C'
            
            ad_type = element
            if element == 'C':
                ad_type = 'A' if 'AR' in line.upper() else 'C'
            elif element == 'O':
                ad_type = 'OA'
            elif element == 'N':
                ad_type = 'NA'

            charge = 0.000
            pdbqt_line = f"ATOM  {atom_count:>5} {atom_name:<4} {res_name:>3} {chain_id}{res_num:>4}    {x:>8.3f}{y:>8.3f}{z:>8.3f}  1.00  0.00    {charge:>6.3f} {ad_type:<2}"
            pdbqt_lines.append(pdbqt_line)

    pdbqt_lines.append("ENDROOT")
    pdbqt_lines.append(f"TORSDOF {max(0, atom_count // 3)}")
    return "\n".join(pdbqt_lines)

