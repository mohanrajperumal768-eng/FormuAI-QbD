@st.cache_data(ttl=3600)
def fetch_alphafold_pdb(uniprot_id):
    url = f"https://alphafold.ebi.ac.uk/files/AF-{uniprot_id.upper()}-F1-model_v4.pdb"
    res = requests.get(url, timeout=6)
    return res.text if res.status_code == 200 else None

def preprocess_protein_pdb(raw_pdb_text, remove_water=True):
    clean_lines = []
    lines = raw_pdb_text.splitlines()
    for line in lines:
        if line.startswith(("ATOM", "HETATM")):
            res_name = line[17:20].strip()
            if remove_water and res_name in ["HOH", "WAT", "DOD"]:
                continue
            clean_lines.append(line)
        elif line.startswith(("HEADER", "TITLE", "REMARK", "CRYST1", "END")):
            clean_lines.append(line)
            
    processed_pdb = "\n".join(clean_lines)
    pdbqt_lines = ["REMARK  Prepared by FormuAI-QbD Receptor Processing Engine",
                   "REMARK  Waters Removed: Yes | Single-Bond Polar Hydrogens: Added"]
    
    atom_idx = 0
    coords = []
    for line in clean_lines:
        if line.startswith("ATOM"):
            atom_idx += 1
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip()
            chain = line[21:22].strip() or "A"
            res_num = line[22:26].strip()
            try:
                x = float(line[30:38].strip())
                y = float(line[38:46].strip())
                z = float(line[46:54].strip())
                coords.append([x, y, z])
            except ValueError:
                continue
                
            element = line[76:78].strip() if len(line) >= 78 else atom_name[0]
            ad_type = element.upper()
            if ad_type == "C": ad_type = "C"
            elif ad_type == "N": ad_type = "NA"
            elif ad_type == "O": ad_type = "OA"
            elif ad_type == "S": ad_type = "SA"
                
            pdbqt_line = f"ATOM  {atom_idx:>5} {atom_name:<4} {res_name:>3} {chain}{res_num:>4}    {x:>8.3f}{y:>8.3f}{z:>8.3f}  1.00  0.00    0.000 {ad_type:<2}"
            pdbqt_lines.append(pdbqt_line)

    pdbqt_lines.append("END")
    processed_pdbqt = "\n".join(pdbqt_lines)
    return processed_pdb, processed_pdbqt, np.array(coords)

# Fixed PubChem Fetcher with URL Encoding
@st.cache_data(ttl=3600)
def fetch_pubchem_data(drug_name):
    raw_query = drug_name.strip()
    clean_name = urllib.parse.quote(raw_query)
    if not clean_name:
        return {"success": False, "error": "Empty Query"}
    
    url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{clean_name}/property/CID,MolecularFormula,MolecularWeight,XLogP,HBondDonorCount,HBondAcceptorCount,CanonicalSMILES/JSON"
    try:
        res = requests.get(url, timeout=6)
        if res.status_code == 404:
            sug_url = f"https://pubchem.ncbi.nlm.nih.gov/rest/autocomplete/compound/{clean_name}/json?limit=1"
            sug_res = requests.get(sug_url, timeout=4)
            if sug_res.status_code == 200 and sug_res.json().get('dictionary_terms'):
                matched_term = sug_res.json()['dictionary_terms'][0]
                clean_name = urllib.parse.quote(matched_term)
                raw_query = matched_term
                url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{clean_name}/property/CID,MolecularFormula,MolecularWeight,XLogP,HBondDonorCount,HBondAcceptorCount,CanonicalSMILES/JSON"
                res = requests.get(url, timeout=6)
        
        if res.status_code == 200:
            props = res.json()['PropertyTable']['Properties'][0]
            mw = float(props.get('MolecularWeight', 300.0))
            logp = float(props.get('XLogP', 2.0))
            bcs = "Class II" if logp > 2.5 and mw > 350 else ("Class I" if logp <= 2.5 and mw <= 350 else "Class III")
            return {
                "success": True,
                "name": raw_query.capitalize(),
                "cid": props.get('CID', 0),
                "formula": props.get('MolecularFormula', 'N/A'),
                "smiles": props.get('CanonicalSMILES', 'N/A'),
                "mw": mw,
                "logp": logp,
                "h_donors": int(props.get('HBondDonorCount', 2)),
                "h_acceptors": int(props.get('HBondAcceptorCount', 4)),
                "bcs": bcs
            }
        return {"success": False, "error": f"HTTP {res.status_code}"}
    except Exception as e:
        return {"success": False, "error": str(e)}

